"""Generate lazy Extism guest imports from the pinned FluentCI engine schema."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generated(schema):
    signatures = {name: {"input": "input" in fn, "output": "output" in fn,
                         "json": fn.get("input", {}).get("contentType") == "application/json"}
                  for name, fn in schema["imports"].items()}
    purs = ["-- Generated by scripts/generate-pdk.py. Do not edit.",
            "module FluentCI.Plugin.Internal.Imports where", "", "import Prelude (Unit)",
            "import Effect (Effect)", "", "foreign import invoke :: String -> String -> Effect String", "foreign import signatureJson :: String"]
    js = ["// Generated from schema/host.json. No host runtime is instantiated.",
          "const signatures = Object.freeze(" + json.dumps(signatures, indent=2) + ");",
          "export const signatureJson = JSON.stringify(signatures);", '''
const failure = (kind, operation, message) => Object.assign(new Error(message), { kind, operation });
function invokeRaw(name, input) {
  const signature = signatures[name];
  if (!signature) throw failure("missing-host", name, "Unknown FluentCI host function");
  if (typeof Host === "undefined" || typeof Host.getFunctions !== "function")
    throw failure("missing-host", name, "Run this code inside a FluentCI Wasm plugin");
  const functions = Host.getFunctions();
  if (typeof functions[name] !== "function")
    throw failure("missing-host", name, "The engine does not expose this function");
  if (signature.json) {
    try { JSON.parse(input); }
    catch (_) { throw failure("invalid-input", name, "Expected a JSON wire payload"); }
  }
  try {
    const result = signature.input ? functions[name](Memory.fromString(input).offset) : functions[name]();
    return signature.output ? Memory.find(result).readString() : "";
  } catch (error) {
    throw failure("host-failure", name, error instanceof Error ? error.message : String(error));
  }
}
export const invoke = name => input => () => invokeRaw(name, input);
''']
    for name, signature in signatures.items():
        argument = "String -> " if signature["input"] else ""
        result = "String" if signature["output"] else "Unit"
        purs.append(f"foreign import {name} :: {argument}Effect {result}")
        expression = f'invokeRaw("{name}", value)' if signature["input"] else f'invokeRaw("{name}", "")'
        if not signature["output"]:
            expression = "{ " + expression + "; }"
        js.append(f'export const {name} = {"value => " if signature["input"] else ""}() => {expression};')
    yield ROOT / "src/FluentCI/Plugin/Internal/Imports.purs", "\n".join(purs) + "\n"
    yield ROOT / "src/FluentCI/Plugin/Internal/Imports.js", "\n".join(js) + "\n"
    declarations = ["// Generated guest ABI. Compile user exports with Extism JS PDK.",
                    'declare module "extism:host" { interface user {']
    for name, fn in schema["imports"].items():
        declarations.append(f'  {name}({"value: I64" if "input" in fn else ""}): {"I64" if "output" in fn else "void"};')
    declarations.append("} }")
    yield ROOT / "schema/imports.d.ts", "\n".join(declarations) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--engine", type=Path, help="Verify the pinned snapshot against an engine checkout")
    options = parser.parse_args()
    raw = (ROOT / "schema/host.json").read_bytes()
    provenance = json.loads((ROOT / "schema/source.json").read_text())
    if hashlib.sha256(raw).hexdigest() != provenance["sha256"]:
        raise SystemExit("Schema snapshot changed: update schema/source.json with its engine revision and digest")
    schema = json.loads(raw)
    if options.engine and schema != json.loads((options.engine / "schema/host.json").read_text()):
        raise SystemExit("Guest schema differs from the engine: refresh the snapshot and regenerate")
    for path, source in generated(schema):
        if options.check:
            if not path.exists() or path.read_text() != source:
                raise SystemExit(f"Stale generated guest imports: {path.relative_to(ROOT)}")
        else:
            path.write_text(source)
    print(f"Guest ABI: {len(schema['imports'])} imports match the pinned engine schema")


if __name__ == "__main__":
    main()
